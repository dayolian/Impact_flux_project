matched = 0
unmatched = []

for (cid, clon, clat, ccat) in calibration:
    # find nearest Daubar site
    best = None
    best_d = 999.0
    for (did, dlat, dlon) in daubar_sites:
        d = dist(clat, clon, dlat, dlon)
        if d < best_d:
            best_d = d
            best = (did, dlat, dlon)

    if best_d <= MATCH_TOL_DEG:
        did, dlat, dlon = best
        print(f"{cid:>4} {ccat:5} {clon:>8.3f} {clat:>7.3f} | "
              f"{did:25} {dlon:>8.3f} {dlat:>7.3f} {best_d:>6.3f}")
        matched += 1
    else:
        did, dlat, dlon = best
        unmatched.append((cid, ccat, clon, clat, did, dlat, dlon, best_d))

