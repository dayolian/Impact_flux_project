def lon_dist(a, b):
    """Minimum angular distance between two longitudes (0-360)."""
    d = abs(a - b) % 360
    return d if d <= 180 else 360 - d

def dist(lat1, lon1, lat2, lon2):
    """Simple Euclidean distance in degrees (good enough for small separations)."""
    dlat = lat1 - lat2
    dlon = lon_dist(lon1, lon2)
    return math.sqrt(dlat**2 + dlon**2)

