matched = 0
unmatched = []

for (cid, clon, clat, ccat) in calibration:
    best = None
    best_d = 999.0
    for row in daubar2013:
        d = dist(clat, clon, row[1], row[2])
        if d < best_d:
            best_d = d
            best = row

    if best_d <= MATCH_TOL_DEG:
        site, dlat, dlon, bctx, bdate, actx, adate, hirise = best
        print(f"{cid:>4} {ccat:5} | {site:>4} {best_d:>6.3f} | "
              f"{bctx:20} {bdate:12} {actx:20} {adate:12} | {hirise}")
        matched += 1
    else:
        unmatched.append((cid, ccat, clon, clat, best, best_d))

